insert into public.lessons(id, topic_id, title, summary, estimated_minutes, position, licence, attribution, i18n)
select x.id,t.id,x.title,x.summary,25,0,'original','Авторский конспект OlympAI', '{}'::jsonb
from curriculum_content x join public.topics t on t.slug=x.slug
on conflict(id) do update set title=excluded.title,summary=excluded.summary,estimated_minutes=excluded.estimated_minutes,i18n='{}'::jsonb;

delete from public.lesson_blocks where lesson_id in (select id from curriculum_content);
insert into public.lesson_blocks(lesson_id,kind,heading,body,position)
select x.id,b.kind,b.heading,b.body,b.position from curriculum_content x
cross join lateral jsonb_to_recordset(x.blocks) as b(kind text, heading text, body text, position smallint);

insert into public.quiz_questions(id,topic_id,lesson_id,prompt,options,correct_index,explanation,position,licence,attribution)
select q.id,t.id,x.id,q.prompt,q.options,q.correct_index,q.explanation,q.position,'original','Авторская проверка OlympAI'
from curriculum_content x join public.topics t on t.slug=x.slug
cross join lateral jsonb_to_recordset(x.questions) as q(id text,prompt text,options text[],correct_index smallint,explanation text,position smallint)
on conflict(id) do update set prompt=excluded.prompt,options=excluded.options,correct_index=excluded.correct_index,explanation=excluded.explanation;
