-- Everything about an olympiad except when it happens.
--
-- The catalogue held a name, a subject and a link, which is enough to pick a
-- target and not enough to decide whether it is your target. This adds the
-- facts a student actually asks for — what the papers look like, who may
-- enter, how you get there — and it adds them in both languages, because a
-- Russian interface wrapped around English-only content is half a translation.
--
-- The rule for what goes in here is the same rule that keeps dates out: only
-- what is structural and stays put. The shape of the papers, the age limit,
-- the founding year and the official address change rarely or never. The
-- sitting date, the host country, the fee and this year's registration
-- procedure change annually, and the only trustworthy source for those is the
-- organiser's own page — which every row carries a link to.
--
-- Where a fact was not solid it is null rather than guessed. A blank line in a
-- detail panel costs a student nothing; a confident wrong one costs them a
-- deadline.

alter table public.competitions
  add column if not exists region text,
  add column if not exists founded integer,
  add column if not exists official_url text,
  add column if not exists papers_url text,
  add column if not exists age_rule text;

-- The prose, one row per language. Separate from the competition so a third
-- language is a set of rows rather than a set of columns, and so a missing
-- translation is an absent row rather than a null that renders as a gap.
create table if not exists public.competition_details (
  competition_id uuid not null references public.competitions(id) on delete cascade,
  locale text not null check (locale in ('en', 'ru')),
  summary text not null,
  format text,
  route text,
  primary key (competition_id, locale)
);

alter table public.competition_details enable row level security;

drop policy if exists "Signed-in users can view competition details" on public.competition_details;
create policy "Signed-in users can view competition details"
  on public.competition_details for select to authenticated using (true);

