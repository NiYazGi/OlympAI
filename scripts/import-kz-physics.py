"""Builds supabase/migrations/202608190035_kz_physics_archive.sql from the
transcribed Kazakhstan physics olympiad papers (olympiads.bc-pf.org).

    python -I scripts/import-kz-physics.py <transcription dir> <project root>

The transcription dir holds batch-*.json (paper metadata: id, olympiad, year,
grades, tour, source_url) and papers/<paper-id>.json (problems, transcribed
from the PDFs by reading each page, with LaTeX and cropped figures in
figures/). Figures are copied to public/tasks/physics/.

Like the maths importer, re-run only before the migration has been applied
anywhere; a changed import after that goes in a new migration.
"""
import collections
import glob
import json
import os
import re
import shutil
import sys

SRC, ROOT = sys.argv[1], sys.argv[2]

TOPICS = {'mechanics', 'thermodynamics', 'electrodynamics', 'optics', 'oscillations-waves', 'modern-physics'}
BASE = {'national': 4, 'oblast': 3}
MINUTES = {2: 25, 3: 40, 4: 60, 5: 75}
FIGURE = re.compile(r'^!\[[^\]]*\]\(/tasks/physics/([A-Za-z0-9_.-]+\.png)\)$', re.M)

meta = {}
for path in glob.glob(os.path.join(SRC, 'batch-*.json')):
    for paper in json.load(open(path, encoding='utf-8')):
        meta[paper['id']] = paper

tasks, problems_seen, issues = [], 0, []
skipped = collections.Counter()
missing_papers = sorted(set(meta) - {os.path.basename(p)[:-5] for p in glob.glob(os.path.join(SRC, 'papers', '*.json'))})
fig_dest = os.path.join(ROOT, 'public', 'tasks', 'physics')
os.makedirs(fig_dest, exist_ok=True)

for path in sorted(glob.glob(os.path.join(SRC, 'papers', '*.json'))):
    data = json.load(open(path, encoding='utf-8'))
    pid = data['paper']
    paper = meta[pid]
    language = data.get('language', 'ru')
    for s in data.get('skipped', []):
        skipped[s.get('reason', 'skipped')[:60]] += 1
    probs = [p for p in data.get('problems', []) if p.get('solvable_on_paper', True)]
    for p in data.get('problems', []):
        if not p.get('solvable_on_paper', True):
            skipped['not solvable on paper'] += 1
    count = len(probs)
    for p in probs:
        problems_seen += 1
        n = int(p['number'])
        tid = f'{pid}-{n}'
        statement = p['statement'].strip()
        topic = p.get('topic')
        if topic not in TOPICS:
            issues.append(f'{tid}: unknown topic {topic!r}, filed under mechanics')
            topic = 'mechanics'
        for name in FIGURE.findall(statement):
            src = os.path.join(SRC, 'figures', name)
            if not os.path.exists(src):
                issues.append(f'{tid}: figure {name} referenced but missing')
                continue
            shutil.copyfile(src, os.path.join(fig_dest, name))
        if re.search(r'!\[[^\]]*\]\((?!/tasks/physics/)', statement):
            issues.append(f'{tid}: image outside /tasks/physics/')
        if statement.count('\\(') != statement.count('\\)') or statement.count('\\[') != statement.count('\\]'):
            issues.append(f'{tid}: unbalanced math delimiters')

        grades = sorted(paper['grades'])
        gmin, gmax = grades[0], grades[-1]
        grade_label = f'{gmin}' if gmin == gmax else f'{gmin}–{gmax}'
        tour = f', {paper["tour"]} тур' if paper['tour'] != 1 or paper['olympiad'] == 'national' and paper['year'] == 2020 else ''
        name = (p.get('name') or '').strip().strip('«»"')
        title = f'{paper["olympiad_name"]} по физике {paper["year"]}, {grade_label} класс — задача {n}'
        if name:
            title += f'. «{name}»'
        source = f'{paper["olympiad_name"]} по физике, {paper["year"]}, {grade_label} класс{tour}'
        if language == 'kk':
            source += ' (на казахском)'
        later_half = count > 1 and n > (count + 1) // 2
        difficulty = max(1, min(5, BASE[paper['olympiad']] + (1 if later_half else 0)))
        tasks.append({
            'id': tid, 'topic': topic, 'title': title, 'problem': statement, 'difficulty': difficulty,
            'minutes': MINUTES[difficulty], 'source': source, 'source_url': paper['source_url'] or None,
            'gmin': gmin, 'gmax': gmax, 'language': language,
        })

ids = collections.Counter(t['id'] for t in tasks)
assert not [i for i, c in ids.items() if c > 1], 'duplicate task ids'


def q(value):
    if value is None:
        return 'null'
    if isinstance(value, int):
        return str(value)
    assert '$phys$' not in value
    return f'$phys${value}$phys$'


out = [
    "-- Kazakhstan physics olympiad archive (olympiads.bc-pf.org): national and",
    "-- regional rounds, grades 9-11, theory problems.",
    "--",
    "-- Generated by scripts/import-kz-physics.py; do not edit by hand. The source",
    "-- papers are PDFs, so each problem was transcribed from the page images —",
    "-- text with LaTeX in \\( \\) and \\[ \\], figures cropped from the PDF into",
    "-- public/tasks/physics/ and referenced as ![…](/tasks/physics/…) lines that",
    "-- components/math-text.tsx renders. Papers only published in Kazakh are kept",
    "-- in Kazakh. Experimental tours and problems that need lab equipment are left",
    "-- out. Grades come from the paper; a paper set to several grades carries the",
    "-- range. Difficulty: the round's level, plus one for the later half of a paper.",
    "--",
    "-- Licence: recorded as 'unknown'; confirm the terms before publishing.",
    "",
]
cols = '(id, subject_id, topic_id, title, problem, difficulty, estimated_minutes, source, source_url, licence, attribution, grade_min, grade_max)'
for start in range(0, len(tasks), 50):
    chunk = tasks[start:start + 50]
    out.append(f'insert into public.tasks {cols}')
    out.append("select v.id, s.id, t.id, v.title, v.problem, v.difficulty, v.minutes, v.source, v.source_url, 'unknown',")
    out.append("       'Казахстанские олимпиады по физике, olympiads.bc-pf.org', v.gmin, v.gmax")
    out.append('from (values')
    out.append(',\n'.join('  (' + ', '.join([q(t['id']), q(t['topic']), q(t['title']), q(t['problem']), q(t['difficulty']),
                                              q(t['minutes']), q(t['source']), q(t['source_url']), q(t['gmin']), q(t['gmax'])]) + ')'
                          for t in chunk))
    out.append(') as v(id, topic_slug, title, problem, difficulty, minutes, source, source_url, gmin, gmax)')
    out.append("join public.subjects s on s.slug = 'physics'")
    out.append('join public.topics t on t.subject_id = s.id and t.slug = v.topic_slug')
    out.append('on conflict (id) do nothing;')
    out.append('')

migration = os.path.join(ROOT, 'supabase', 'migrations', '202608190035_kz_physics_archive.sql')
open(migration, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))

report = {
    'papers_transcribed': len(glob.glob(os.path.join(SRC, 'papers', '*.json'))),
    'papers_missing': missing_papers,
    'tasks': len(tasks),
    'by_topic': collections.Counter(t['topic'] for t in tasks),
    'by_grades': collections.Counter(f"{t['gmin']}-{t['gmax']}" for t in tasks),
    'by_language': collections.Counter(t['language'] for t in tasks),
    'by_olympiad': collections.Counter(t['id'].split('-')[1] for t in tasks),
    'skipped': skipped,
    'issues': issues,
    'figures': len(os.listdir(fig_dest)),
}
json.dump(report, open(os.path.join(SRC, 'import-report.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1, default=dict)
print(json.dumps(report, ensure_ascii=True, indent=1, default=dict))
